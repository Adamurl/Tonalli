"""Validate editorial records and generate a review copy and transactional SQL."""

import argparse
import json
from pathlib import Path
import re
import sys

BACKEND = Path(__file__).resolve().parents[1]
ROOT = BACKEND.parent
sys.path.insert(0, str(BACKEND))

from app.calendar_conversion import DAY_SIGNS

CONTENT_FIELDS = {
    "description": "Main-page description",
    "meaning_and_glyph": "Name and glyph",
    "symbolism": "Meaning and symbolism",
    "cultural_context": "Stories and cultural context",
}
RECORD_FIELDS = {"name", "english", "position", *CONTENT_FIELDS}
CONTENT_DIR = ROOT / "content" / "day-signs"
SQL_PATH = BACKEND / "sql" / "day_sign_content.sql"
PREVIEW_PATH = CONTENT_DIR / "preview.md"


def load_records(path: Path) -> list[dict]:
    records = json.loads(path.read_text())
    if not isinstance(records, list) or len(records) != len(DAY_SIGNS):
        raise ValueError("Expected exactly twenty day-sign records")
    for position, (record, identity) in enumerate(zip(records, DAY_SIGNS), 1):
        if not isinstance(record, dict) or set(record) != RECORD_FIELDS:
            raise ValueError(f"Record {position} must match the seven-column contract")
        if (
            type(record["position"]) is not int
            or record["position"] != position
            or record["name"] != identity["nahuatl"]
            or record["english"] != identity["english"]
        ):
            raise ValueError(f"Record {position} does not match the calendar identity")
        for field in CONTENT_FIELDS:
            text = record[field]
            if not isinstance(text, str) or len(text.split()) < 40:
                raise ValueError(f"{record['name']}.{field} needs a complete description")
            if re.search(r"\[S\d+\]|https?://|\b(?:the book|the source|translated passage)\b", text, re.I):
                raise ValueError(f"{record['name']}.{field} contains display attribution")
        overview = record["description"]
        if "\n" in overview or not 100 <= len(overview.split()) <= 180:
            raise ValueError(f"{record['name']} needs one main-page paragraph of 100 to 180 words")
    return records


def render_sql(records: list[dict]) -> str:
    payload = json.dumps(records, ensure_ascii=False, indent=2)
    delimiter = "$tonalli_content$"
    if delimiter in payload or "$tonalli_update$" in payload:
        raise ValueError("Content contains the SQL payload delimiter")
    return f"""-- Generated by backend/scripts/prepare_day_sign_content.py. Review before applying.
begin;

do $tonalli_update$
declare
    item record;
    matched integer;
begin
    for item in
        select * from jsonb_to_recordset({delimiter}{payload}{delimiter}::jsonb)
        as content(
            name text, english text, position integer,
            description text, meaning_and_glyph text,
            symbolism text, cultural_context text
        )
    loop
        update public.day_signs set
            description = item.description,
            meaning_and_glyph = item.meaning_and_glyph,
            symbolism = item.symbolism,
            cultural_context = item.cultural_context
        where name = item.name and position = item.position and english = item.english;
        get diagnostics matched = row_count;
        if matched <> 1 then
            raise exception 'Expected one matching row for %, found %', item.name, matched;
        end if;
    end loop;
end
$tonalli_update$;

commit;
"""


def render_preview(records: list[dict]) -> str:
    lines = [
        "# Day-sign editorial preview",
        "",
        "Editorial content generated from records.json. Publication status is recorded in backups/*.manifest.json.",
        "",
    ]
    for record in records:
        lines.extend([f"## {record['position']}. {record['name']} · {record['english']}", ""])
        for field, title in CONTENT_FIELDS.items():
            lines.extend([f"### {title}", "", record[field], ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated artifacts differ")
    args = parser.parse_args()
    records = load_records(CONTENT_DIR / "records.json")
    outputs = {SQL_PATH: render_sql(records), PREVIEW_PATH: render_preview(records)}
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Regenerate {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print("Validated twenty signs, eighty descriptions, and two generated artifacts. No database writes.")


if __name__ == "__main__":
    main()
